-- 1. Sequences for Auto-Increment Primary Keys
CREATE SEQUENCE SEQ_DEPARTMENTS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_USERS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_REQUESTS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_REQUEST_HISTORY
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_FEEDBACK
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_NOTIFICATIONS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- 2. DEPARTMENTS Table
CREATE TABLE DEPARTMENTS (
    DEPARTMENT_ID   NUMBER PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION     VARCHAR2(500),
    ACTIVE_STATUS   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_DEPT_STATUS CHECK (ACTIVE_STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- 3. USERS Table
CREATE TABLE USERS (
    USER_ID         NUMBER PRIMARY KEY,
    NAME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH   VARCHAR2(256) NOT NULL,
    PASSWORD_SALT   VARCHAR2(64) NOT NULL,
    ROLE            VARCHAR2(20) NOT NULL,
    DEPARTMENT_ID   NUMBER,
    PHONE           VARCHAR2(20),
    ACCOUNT_STATUS  VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_USERS_DEPT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS(DEPARTMENT_ID) ON DELETE SET NULL,
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('STUDENT', 'STAFF', 'ADMIN')),
    CONSTRAINT CHK_USER_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- 4. REQUESTS Table
CREATE TABLE REQUESTS (
    REQUEST_ID          NUMBER PRIMARY KEY,
    TRACKING_CODE       VARCHAR2(30) NOT NULL UNIQUE,
    USER_ID             NUMBER NOT NULL,
    CATEGORY            VARCHAR2(50) NOT NULL,
    TITLE               VARCHAR2(200) NOT NULL,
    DESCRIPTION         VARCHAR2(2000) NOT NULL,
    LOCATION            VARCHAR2(150) NOT NULL,
    URGENCY             NUMBER(1) NOT NULL,
    IMPACT              NUMBER(1) NOT NULL,
    LOCATION_WEIGHT     NUMBER(1) NOT NULL,
    PRIORITY_SCORE      NUMBER NOT NULL,
    PRIORITY            VARCHAR2(20) NOT NULL,
    STATUS              VARCHAR2(20) DEFAULT 'SUBMITTED' NOT NULL,
    DEPARTMENT_ID       NUMBER,
    ASSIGNED_STAFF_ID   NUMBER,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESOLVED_AT         TIMESTAMP,
    CLOSED_AT           TIMESTAMP,
    CANCELLED_AT        TIMESTAMP,
    CANCELLATION_REASON VARCHAR2(500),
    CONSTRAINT FK_REQ_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_REQ_DEPT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS(DEPARTMENT_ID) ON DELETE SET NULL,
    CONSTRAINT FK_REQ_STAFF FOREIGN KEY (ASSIGNED_STAFF_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL,
    CONSTRAINT CHK_REQ_URGENCY CHECK (URGENCY BETWEEN 1 AND 4),
    CONSTRAINT CHK_REQ_IMPACT CHECK (IMPACT BETWEEN 1 AND 4),
    CONSTRAINT CHK_REQ_LOC_WEIGHT CHECK (LOCATION_WEIGHT BETWEEN 1 AND 3),
    CONSTRAINT CHK_REQ_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT CHK_REQ_STATUS CHECK (STATUS IN ('SUBMITTED', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED'))
);

-- 5. REQUEST_HISTORY Table
CREATE TABLE REQUEST_HISTORY (
    HISTORY_ID      NUMBER PRIMARY KEY,
    REQUEST_ID      NUMBER NOT NULL,
    ACTION_TYPE     VARCHAR2(50) NOT NULL,
    OLD_STATUS      VARCHAR2(20),
    NEW_STATUS      VARCHAR2(20),
    REMARKS         VARCHAR2(1000),
    ACTOR_USER_ID   NUMBER NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_HIST_REQ FOREIGN KEY (REQUEST_ID) REFERENCES REQUESTS(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT FK_HIST_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 6. FEEDBACK Table
CREATE TABLE FEEDBACK (
    FEEDBACK_ID     NUMBER PRIMARY KEY,
    REQUEST_ID      NUMBER NOT NULL UNIQUE,
    STUDENT_USER_ID NUMBER NOT NULL,
    RATING          NUMBER(1) NOT NULL,
    COMMENTS        VARCHAR2(1000),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,
    CONSTRAINT FK_FB_REQ FOREIGN KEY (REQUEST_ID) REFERENCES REQUESTS(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT FK_FB_STUDENT FOREIGN KEY (STUDENT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_FB_RATING CHECK (RATING BETWEEN 1 AND 5)
);

-- 7. NOTIFICATIONS Table
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID   NUMBER PRIMARY KEY,
    RECIPIENT_USER_ID NUMBER NOT NULL,
    REQUEST_ID        NUMBER,
    NOTIFICATION_TYPE VARCHAR2(50) NOT NULL,
    MESSAGE           VARCHAR2(500) NOT NULL,
    IS_READ           NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    READ_AT           TIMESTAMP,
    CONSTRAINT FK_NOTIF_USER FOREIGN KEY (RECIPIENT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTIF_REQ FOREIGN KEY (REQUEST_ID) REFERENCES REQUESTS(REQUEST_ID) ON DELETE SET NULL,
    CONSTRAINT CHK_NOTIF_READ CHECK (IS_READ IN (0, 1))
);
